"""
Should this reach the wearer's lenses right now?

This module exists because the honest answer, until now, was "there is no
such code". The repository had a policy layer deciding whether pushes are
allowed, a ledger recording reactions, a queue described at length in DESIGN.md
and documents/07 and documents/08 -- and no shipped function that ever made
the decision. The only push decision in the repo lived in
``experiments/soak.py``, scoring candidates generated by ``sim/`` against a
virtual wearer. That is a useful experiment and it is not a product.

So: here is the decision, as a PURE function. It takes candidates, a policy
and a budget, and returns what should happen to each. It does not import
bleak, does not touch a radio, does not write to the glasses, and does not
read the ledger. That is deliberate on two counts.

  Testability. Every claim this project makes about interrupt behaviour has to
  be checkable with no hardware, because there is no hardware. A function
  with no I/O can be measured; a function that writes to a BLE characteristic
  cannot be measured at all, which is the state the interrupt logic was in.

  Separation of "should this interrupt" from "how does an interrupt happen".
  The second is ``g1_driver.send_text_packet`` and it is unchanged and
  unmeasured. Mixing them would mean that any test of the DECISION required a
  radio, so the decision would stay untested forever.

THE ORDER OF THE GATES, and it is not arbitrary:

  1. BUDGET      hard constraint, never overridden by evidence. The design
                 principle in policy.py is that being out of budget is not a
                 matter of evidence, so it is checked first.
  2. AXIS        ``push_enabled`` -- with no label history this resolves OFF.
  3. ELIGIBILITY the G2 deterministic rules. A candidate that fails them is
                 still QUEUED, never dropped. Silence is the default state and
                 dropping is the one outcome this system is not allowed to
                 choose silently.
  4. ORDER       urgency, deterministic. Ties broken by source so the same
                 input always produces the same output; a queue that reorders
                 itself run to run is not auditable.

The budget is checked against the SAME constants the policy predicate uses
(``MAX_PUSHES_PER_HOUR``/``MAX_PUSHES_PER_DAY``), by re-resolving the axis
after each push rather than by duplicating the arithmetic here. One place owns
the limit. If it were copied into this module the two would drift, and the
copy is the one nobody would think to update.
"""

