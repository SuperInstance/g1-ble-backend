# The documented on-disk location. DESIGN.md E0 specifies inotify on this
# directory; nothing implemented it, and Candidate.as_spool_json() in sim/
# described the format that nothing read. Both halves now exist and match.
OUTBOX = Path.home() / ".g1" / "outbox"

# The three classes that may interrupt. Anything else queues. This list is
# not a preference: it is the complete G2 rule set, and a class missing from
# it can never interrupt no matter what else is true of it.
PUSHABLE = ("meeting", "blocked_job", "device")

# Minutes before a meeting at which it is worth interrupting. G2 says T-10.
MEETING_LEAD_MIN = 10.0

# A blocked job becomes eligible after this long. G2 says > 120s.
BLOCKED_JOB_AFTER_S = 120

# Battery level below which a device alert may interrupt.
BATTERY_FLOOR_PCT = 10


@dataclass(frozen=True)
class Candidate:
    """One thing that might be worth saying. Never discarded, only ordered."""

    source: str
    cls: str
    line: str
    ts: datetime
    subject: str = ""
    keywords: tuple[str, ...] = ()
    blocked: bool = False
    accepted: bool = True
    elapsed_s: int = 0
    minutes_until: Optional[float] = None
    meta: dict = field(default_factory=dict)

    @classmethod
    def from_json(cls, raw: dict) -> "Candidate":
        """
        Parse one spool record. Accepts ``class`` as well as ``cls``.

        That tolerance is not politeness, it is a bug fix. ``sim/events.py``
        writes the documented spool format with the key ``"class"`` --
        ``Candidate.as_spool_json()`` -- because that is what it has always
        written. This parser originally read only ``"cls"``, matching its own
        dataclass field, so every candidate the simulator produced parsed
        with ``cls="unknown"``, failed G2 eligibility with "class 'unknown'
        is not in the G2 rule set", and queued forever.

        Nothing would have raised. The queue would simply have decided that
        nothing was ever worth interrupting, which reads exactly like a
        working system being conservative, and the cause -- a key name -- is
        nowhere in the output. Found by round-tripping the simulator through
        its own documented format; it is the first defect found by the rule
        "if two modules agree on a contract, test the contract."

        ``class`` is preferred on read because it is the documented external
        field name; ``cls`` is accepted for this module's own writer.
        """
        ts = raw.get("ts")
        if isinstance(ts, str):
            parsed = datetime.fromisoformat(ts)
            # A naive stamp is almost always UTC from an external producer;
            # local time is what the budget is counted in.
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
        elif isinstance(ts, datetime):
            parsed = ts if ts.tzinfo else ts.replace(tzinfo=timezone.utc)
        else:
            parsed = datetime.now(timezone.utc)
        return cls(
            source=str(raw.get("source", "unknown")),
            cls=str(raw.get("class", raw.get("cls", "unknown"))),
            line=str(raw.get("line", "")),
            ts=parsed,
            subject=str(raw.get("subject", "")),
            keywords=tuple(raw.get("keywords") or ()),
            blocked=bool(raw.get("blocked", False)),
            accepted=bool(raw.get("accepted", True)),
            elapsed_s=int(raw.get("elapsed_s", 0) or 0),
            minutes_until=raw.get("minutes_until"),
            meta=dict(raw.get("meta") or {}),
        )

    def as_json(self) -> dict:
        return {
            "source": self.source, "cls": self.cls, "line": self.line,
            "ts": self.ts.isoformat(), "subject": self.subject,
            "keywords": list(self.keywords), "blocked": self.blocked,
            "accepted": self.accepted, "elapsed_s": self.elapsed_s,
            "minutes_until": self.minutes_until, "meta": dict(self.meta),
        }

    # -- G2 ---------------------------------------------------------------
    #
    # Written as one method with no branches on the caller rather than as a
    # table, because the table version is easier to extend and that is the
    # problem: an extension would be an unreviewed change to what can
    # interrupt a person walking down a street.

    def eligible(self, now: datetime) -> tuple[bool, str]:
        """
        The deterministic G2 rules. Returns (eligible, human reason).

        Note the third branch reads a FIELD the caller must supply
        (``meta['battery_pct']``). When it is absent the branch is False,
        which is the conservative direction: a device alert with no battery
        reading queues instead of interrupting on a guess.
        """
        if self.cls == "meeting":
            if not self.accepted:
                return False, "declined invitation; not the wearer's meeting"
            if self.minutes_until is None:
                return False, "no time until start; cannot place it in the window"
            if not (0 <= self.minutes_until <= MEETING_LEAD_MIN):
                return False, f"starts in {self.minutes_until:g}m, outside T-{MEETING_LEAD_MIN:g}"
            return True, f"accepted, starts in {self.minutes_until:g}m (T-{MEETING_LEAD_MIN:g})"

        if self.cls == "blocked_job":
            if not self.blocked:
                return False, "not blocked; nothing to report"
            if self.elapsed_s <= BLOCKED_JOB_AFTER_S:
                return False, f"blocked only {self.elapsed_s}s (<{BLOCKED_JOB_AFTER_S})"
            return True, f"blocked {self.elapsed_s}s (>={BLOCKED_JOB_AFTER_S})"

        if self.cls == "device":
            pct = self.meta.get("battery_pct")
            if pct is None:
                return False, "no battery reading supplied; refusing to guess"
            if pct >= BATTERY_FLOOR_PCT:
                return False, f"battery {pct}% (floor {BATTERY_FLOOR_PCT}%)"
            return True, f"battery {pct}% (below {BATTERY_FLOOR_PCT}%)"

        return False, f"class {self.cls!r} is not in the G2 rule set"

    def urgency(self, now: datetime) -> tuple:
        """
        Sort key, ascending. Lower sorts first.

        Returns a TUPLE, and the tier is separate from the within-tier value.
        An earlier version returned one float mixing units — minutes-until for
        meetings against seconds-blocked for jobs — which made a job blocked
        for ten minutes sort ahead of a meeting starting in two. That was not
        a tuning mistake, it was comparing quantities that do not have a
        common scale, and it looked correct until the numbers were large
        enough to matter.

        Tier order is a judgement and is named here so it can be argued with:
        a meeting is the only candidate with a deadline, so it goes first; a
        dying battery is next because the window to charge is short; a blocked
        job is last because it has already been blocked for two minutes and
        will be blocked for two more, so waiting costs the wearer very
        little. Anything not in the G2 rule set sorts after all pushables.
        """
        if self.cls == "meeting":
            # Within tier: soonest first, so negate the remaining minutes.
            mins = float(self.minutes_until) if self.minutes_until is not None else 1e6
            return (0, mins)
        if self.cls == "device":
            pct = self.meta.get("battery_pct")
            # Lower battery first -> negate so ascending order puts it first.
            return (1, -float(pct)) if pct is not None else (1, 0.0)
        if self.cls == "blocked_job":
            # Longer blocked first.
            return (2, -float(self.elapsed_s))
        return (9, 0.0)


@dataclass(frozen=True)
class Verdict:
    """What happens to one candidate, and why — the audit trail."""

    candidate: Candidate
    action: str                  # "push" | "queue"
    reason: str
    gate: str                    # which gate decided it

    @property
    def is_push(self) -> bool:
        return self.action == "push"


@dataclass
class Budget:
    """
    Pushes already spent, plus whatever evidence exists. Mutable because a
    batch spends the push budget as it goes.

    The counters are the SAME ones policy._resolve_push_enabled reads. They
    are tracked here rather than recomputed from the ledger because the queue
    has to decide a whole batch, and asking "what is left" five times against
    a ledger that will not record any of them yet is not a question with a
    useful answer.

    THE TWO KINDS OF ZERO, which are not the same thing:

      pushes_today / pushes_last_hour  default to 0, and 0 is TRUE. Nothing
                                       has been pushed. There is no push path
                                       yet, and "none spent" is an honest
                                       reading of that.

      label_days / clean_pushes / ...  default to None, and None means
                                       "no source exists". Not 0. A fabricated
                                       0 would let a reader conclude an axis
                                       had been evaluated and found wanting,
                                       when the truth is that it was never
                                       evaluated at all.

    `evidence()` omits the None ones entirely, so policy.resolve() sees them as
    missing and marks those axes unresolved -- which is the documented
    behaviour for absent metrics, rather than a silent zero passing as a
    measurement.
    """

    pushes_today: int = 0
    pushes_last_hour: int = 0
    label_days: Optional[int] = None
    clean_pushes: Optional[int] = None
    n_labels: Optional[int] = None
    queue_worth_rate: Optional[float] = None
    rho: Optional[float] = None
    drill_miss_rate: Optional[float] = None

    def evidence(self) -> dict:
        """
        The dict policy.resolve() consumes. One source of truth.

        NESTED PER AXIS — ``{"push_enabled": {"label_days": 20}}``, not a flat
        ``{"label_days": 20}``. resolve() looks up ``evidence.get(axis.id)``
        and hands that sub-dict to the axis resolver, so a flat dict silently
        resolves every axis to its default with no error. That cost an
        afternoon of "the policy ignores my evidence" before the control arm
        in experiments/queue_gate.py caught it; a flat shape here looks
        completely reasonable and does nothing.
        """
        return {
            "push_enabled": {
                "pushes_today": self.pushes_today,
                "pushes_last_hour": self.pushes_last_hour,
                # Omitted when None: see the class docstring. A present key
                # with a None value would reach `days >= 14` as a TypeError,
                # and a zero would be a lie.
                **({"label_days": self.label_days}
                   if self.label_days is not None else {}),
            },
            "interrupt_gate": ({"clean_pushes": self.clean_pushes}
                               if self.clean_pushes is not None else {}),
            "g1_model": {
                **({"n_labels": self.n_labels}
                   if self.n_labels is not None else {}),
                **({"queue_worth_rate": self.queue_worth_rate}
                   if self.queue_worth_rate is not None else {}),
            },
            "examination_source": ({"rho": self.rho}
                                   if self.rho is not None else {}),
            "detail_generation": ({"drill_miss_rate": self.drill_miss_rate}
                                  if self.drill_miss_rate is not None else {}),
        }

    def spend(self, now: datetime) -> None:
        """Count one push against the budget."""
        self.pushes_today += 1
        self.pushes_last_hour += 1

    # There is deliberately NO method here that recounts pushes_last_hour
    # from timestamps. One was written, and it was dead on arrival: nothing in
    # the shipped package recorded WHEN a push happened, because nothing sent
    # pushes -- this module is dry-run only. A counter that only ever
    # increments is wrong after the first hour, so this was a known gap and
    # not a hidden one.
    #
    # That gap is now CLOSED on the storage side: memory.FeedbackStore grew a
    # `push_events` table plus record_push()/push_counts(), and
    # evidence_from_store() above reads it. The recount lives there rather
    # than here, because it needs a store and this class deliberately has
    # none.
    #
    # Recorded because the audit caught exactly this function once already --
    # written with a docstring about the bug it prevented, called by nothing.
    # The fix was to give it a caller, not to keep the note.


def load_outbox(directory: Path = OUTBOX) -> list[Candidate]:
    """
    Read ``*.json`` from the outbox. The documented ingestion path (DESIGN.md
    E0) that had no implementation.

    A malformed file is skipped with a log line, never a crash: this runs on
    a wearable loop where one bad producer must not take the session down.
    """
    out: list[Candidate] = []
    if not directory.exists():
        return out
    for path in sorted(directory.glob("*.json")):
        try:
            raw = json.loads(path.read_text())
            items = raw if isinstance(raw, list) else [raw]
            for item in items:
                if isinstance(item, dict):
                    out.append(Candidate.from_json(item))
        except (json.JSONDecodeError, OSError, TypeError, ValueError) as exc:
            log.warning("skipping unreadable candidate %s: %s", path.name, exc)
    return out


def rank(candidates: Iterable[Candidate], now: datetime) -> list[Candidate]:
    """
    Order by urgency, reproducibly.

    Eligibility is NOT applied here. This orders everything, pushable or not,
    so the queue shows the wearer (and the audit) what is waiting rather than
    only what survived a gate. Filtering first would hide the candidates the
    system decided to stay silent about, which is exactly the thing that has
    to remain inspectable.
    """
    return sorted(candidates, key=lambda c: (c.urgency(now), c.ts, c.source))


def plan(
    candidates: Iterable[Candidate],
    *,
    budget: Optional[Budget] = None,
    policy: Optional[Policy] = None,
    overrides: Optional[dict] = None,
    store=None,
    now: Optional[datetime] = None,
) -> list[Verdict]:
    """
    Decide every candidate. THE decision function.

    Give it EITHER ``policy`` (a frozen resolution, used when the caller has
    already resolved and wants exactly that) OR ``budget`` (re-resolved per
    candidate, so the budget constrains the whole batch rather than each item
    independently). Passing a frozen ``policy`` together with a ``budget``
    that has evidence in it does NOT do what it looks like: the policy wins
    and the budget is never consulted. That is why ``--queue-label-days``
    appeared to do nothing the first time it was wired — a frozen policy from
    ``policy.load()`` was shadowing the evidence entirely.

    ``overrides`` are the saved manual overrides from ``main.py
    --set-policy``. They are applied on top of every re-resolution, so a
    forced axis and a simulated-evidence axis can coexist.

    ``store``, when given, supplies the auto-suspend state (documents/07:
    one mis-fire mutes that source class for 24h). It is optional and reads
    once, before the loop, because a suspended candidate must come back
    QUEUED rather than dropped -- the queue is the safety net, so a class
    that is quiet for a day is quiet for a day, not gone for a day.

    Re-resolving after each push is the point: five eligible candidates in one
    batch must produce at most ``MAX_PUSHES_PER_HOUR`` pushes between them, and
    the only way to get that from a constraint that already lives in
    policy.py is to ask it again.
    """
    now = now or datetime.now(timezone.utc)
    budget = budget if budget is not None else Budget()
    ordered = rank(candidates, now)
    verdicts: list[Verdict] = []

    # Suspensions are read ONCE, not per candidate: they cannot change while
    # this loop runs, and re-reading the store for every item would put a
    # database query on the path of every decision.
    suspended_classes: dict[str, float] = {}
    if store is not None:
        suspended_classes = suspension_state(store, now.timestamp())

    for cand in ordered:
        pol = policy if policy is not None else resolve(
            budget.evidence(), overrides)

        # 1. budget, via the axis the policy layer already enforces it in
        if not pol.on("push_enabled"):
            d = pol.evidence_for("push_enabled")
            why = d.reason if d else "push_enabled is off"
            verdicts.append(Verdict(cand, "queue", why, "budget/axis"))
            continue

        # 1b. SUSPENDED source class (documents/07: one mis-fire, 24h).
        #
        # Checked after the axis and before eligibility, so the reason
        # reported is the useful one: "this class is quietened" rather than a
        # G2 rule that may or may not have passed anyway.
        #
        # Queued, never dropped. That is the whole invariant -- a suspended
        # candidate is ineligible, and ineligible already means queue. The
        # queue remains the safety net, so a class that is muted for a day is
        # quiet for a day, not gone for a day.
        suspended = suspended_classes
        if cand.cls in suspended:
            until = suspended[cand.cls]
            verdicts.append(Verdict(
                cand, "queue",
                f"source class {cand.cls!r} suspended until "
                f"{datetime.fromtimestamp(until, timezone.utc):%Y-%m-%d %H:%M}",
                "suspended"))
            continue

        # 2. G2 eligibility
        ok, why = cand.eligible(now)
        if not ok:
            verdicts.append(Verdict(cand, "queue", why, "eligibility"))
            continue

        verdicts.append(Verdict(cand, "push", why, "eligible"))
        budget.spend(now)

    return verdicts


def evidence_from_store(store) -> tuple["Budget", dict]:
    """
    Derive a :class:`Budget` from a real :class:`memory.FeedbackStore`.

    This is the bridge that was missing. Every axis in ``policy.py`` names a
    deciding metric, and until now nothing computed any of them from the
    shipped ledger, so every axis resolved to its conservative default
    forever and there was no path by which the policy could ever change.
    That is why ``detail_generation`` was the only load-bearing axis: it was
    the only one whose value anything read, not the only one with evidence.

    THE RULE THAT MATTERS HERE: absent is not zero.

    ``label_days`` with no labelling UI is not ``0 days collected``; it is
    "no source exists". The two resolve to the same axis value today, but
    they mean opposite things to a reader, and only one of them is true. A
    fabricated zero is the more dangerous of the two because it looks like a
    measurement and would let someone conclude the axis had been evaluated
    and found wanting, rather than never evaluated at all. So metrics with no
    source are left ABSENT from the dict, which is what ``policy.resolve()``
    documents as "unresolved -- never guessed".

    Returns ``(budget, provenance)`` where provenance maps each metric name to
    ``"derived"`` or ``"no source"``, so a caller -- or ``--evidence`` -- can
    show which numbers are real.
    """
    prov: dict[str, str] = {}

    def mark(name: str, value=None, source: bool = True):
        prov[name] = "derived" if source else "no source"

    # -- drill_miss_rate: THE ONE METRIC WITH A REAL SOURCE ---------------
    #
    # Derived as misses over (misses + real drills). `drill_deferred` is
    # excluded by construction, since it is a different event kind now. A
    # rate with zero denominator is NOT 0.0 -- it is unmeasurable, and
    # returning 0.0 would say "drills always succeed" when the truth is
    # "no drill has been judged yet".
    try:
        counts = store.counts()
    except Exception as exc:                       # noqa: BLE001
        log.warning("could not read store counts: %s", exc)
        counts = {}

    miss = int(counts.get("drill_miss", 0) or 0)
    expand = int(counts.get("expand", 0) or 0)
    judged = miss + expand
    budget = Budget()
    if judged:
        budget.drill_miss_rate = miss / judged
        mark("drill_miss_rate")
    else:
        mark("drill_miss_rate", None, source=False)

    # -- push budget: counted from recorded attempts, never accumulated ----
    #
    # This used to be `budget.pushes_last_hour`, a counter that `spend()`
    # incremented and nothing ever decremented. That is correct for the span
    # of one plan() call and wrong for a process: a long-running loop would
    # reach 2/2 after two pushes and then refuse forever, with a log full of
    # successful pushes and no explanation. A silent daemon is worse than a
    # broken one, because a broken one gets noticed.
    #
    # So the budget is counted from durable rows (memory.push_events), which
    # is the same construct `Budget.prune` used to be and could not be,
    # because nothing recorded WHEN a push happened. That table exists now.
    prov["pushes_last_hour"] = "derived"
    prov["pushes_today"] = "derived"
    try:
        hourly, daily = store.push_counts()
        budget.pushes_last_hour = hourly
        budget.pushes_today = daily
    except Exception as exc:                       # noqa: BLE001
        log.warning("could not read push counts: %s", exc)
        prov["pushes_last_hour"] = "unavailable: %s" % exc
        prov["pushes_today"] = "unavailable: %s" % exc

    # -- the four with no source at all ------------------------------------
    #
    # Every one of these needs LABELS: a human or a trusted judge saying
    # "this card was/was not worth interrupting me for". `sim/ledger.py` has
    # `label()` and it is called only by experiments/soak.py, against a
    # VirtualWearer. There is no CLI that produces a label and no shipped code
    # that reads one. Until both exist these stay absent on purpose.
    for name in ("label_days", "clean_pushes", "n_labels", "queue_worth_rate",
                 "rho"):
        prov[name] = "no source"

    return budget, prov


# ---------------------------------------------------------------------------
# Stopping, and quieting a bad source
# ---------------------------------------------------------------------------
#
# Two rules the design wrote down and never built:
#   documents/07 "one mis-fire auto-suspends that source class for 24 hours
#                 -- not three. Trust collapses on the second bad
#                 interruption."
#   documents/13 "one `n` in review suspends that push type for 24 h."
#
# Built here as pure state machines with no BLE and no LED, because a rule
# that is neither wired nor tested is indistinguishable from a rule that does
# not exist.

# Where the kill-switch lives. Re-read on every decision cycle rather than
# cached at startup, so a process that has stopped answering its terminal can
# still be stopped. NOT in policy.json: that file is for axis overrides and
# is only read when the policy is resolved, which happens once.
KILL_SWITCH_PATH = Path.home() / ".g1" / "pushing.armed"

# The panel's number, named so it can be argued with. It is a CHOICE, not a
# constant: sim/wearer.py models trust decaying per bad interruption and
# recovering at 0.03/day, and sim/README.md records that the simulator
# deliberately violates this rule -- "the design assumption I violate most
# directly". Nothing here is derived from data, and pretending otherwise
# would be the same mistake as calling queue_worth_rate a measurement of a
# wearer when it is a measurement of a simulation.
SUSPEND_SECONDS = 24 * 3600.0

# Only these can be suspended, because only these can interrupt. Suspending
# something that could never push is a no-op that looks like a safety feature.
SUSPENDABLE = PUSHABLE


def kill_switch_armed(path: Path) -> bool:
    """
    True when the file says pushing is permitted.

    Deliberately a FILE and not a signal or a flag argument. The failure this
    guards against is a process that has stopped responding to the terminal
    that started it, so the stop control has to live somewhere the operator
    can reach without that terminal. Absence of the file means DISARMED:
    if the check fails to run, the safe direction is silence.
    """
    try:
        return path.exists() and path.read_text().strip().lower() in (
            "armed", "1", "true", "yes")
    except OSError as exc:
        log.warning("kill switch unreadable (%s); treating as DISARMED", exc)
        return False


def suspension_state(store, now: Optional[float] = None) -> dict:
    """
    ``{source class: expiry epoch}``, expired entries dropped.

    Returns nothing for a class whose suspension has lapsed, and never
    returns "suspended until further notice". Rule 2 of the anti-starvation
    design: expiry is unconditional, because a class that stays muted
    precisely because nothing is happening to it is muted forever.
    """
    now = time.time() if now is None else float(now)
    try:
        rows = store.suspensions()
    except Exception as exc:                       # noqa: BLE001
        log.warning("could not read suspensions: %s", exc)
        return {}
    alive: dict[str, float] = {}
    for r in rows:
        if r.get("until_ts", 0) > now:
            alive[r["cls"]] = float(r["until_ts"])
    return alive


@dataclass(frozen=True)
class LinkStatus:
    """
    What the radio can actually do right now.

    A struct rather than a check, on purpose. The decision needs to be
    unit-testable without a radio, and there is no G1 on this host -- so the
    testable artefact has to be the DATA, with the logic reading it, rather
    than the logic buried in the driver where it can only be exercised by
    connecting a physical device.

    Both arms are required. The G1 is two BLE peripherals, and
    ``EvenG1Controller.arms`` filters down to whichever are connected, so a
    dead right arm silently reduces the fan-out to one lens rather than
    failing. A card split across one eye is not "half an interruption", it is
    a different and more alarming one: the wearer sees text appear on one
    side of their face with nothing on the other and cannot tell whether the
    glasses are broken or the system is broken.

    ``heartbeat_age_s`` is not decorative. The link drops after roughly 32
    seconds without a 0x25, and ``_heartbeat_loop`` swallows its exceptions
    and only logs a warning -- so a heartbeat task that has died looks exactly
    like a healthy link from every other observable. Age is the only signal
    that distinguishes them.
    """

    left_ok: bool = False
    right_ok: bool = False
    mtu_left: int = 23
    mtu_right: int = 23
    heartbeat_age_s: Optional[float] = None
    fault: Optional[str] = None

    MIN_MTU = 24        # > 23 means the default ATT MTU was beaten
    MAX_HEARTBEAT_AGE = 20.0

    def check(self) -> tuple[bool, str]:
        """
        Can this link carry a push? Returns (ok, reason).

        Every failure is a REFUSAL, never a degradation. The alternative --
        push on one arm and hope -- is what makes an interruption confusing
        rather than merely late.
        """
        if self.fault:
            return False, f"driver reports a fault: {self.fault}"
        if not self.left_ok:
            return False, "left arm not connected"
        if not self.right_ok:
            return False, ("right arm not connected -- pushing on one lens "
                           "would show a partial card, so it is refused")
        if self.mtu_left <= 23 or self.mtu_right <= 23:
            return False, (f"MTU not negotiated (L={self.mtu_left} "
                           f"R={self.mtu_right}); notifications do not flow "
                           f"at the default 23")
        if self.heartbeat_age_s is None:
            return False, "no heartbeat ever observed; cannot prove the link is up"
        if self.heartbeat_age_s > self.MAX_HEARTBEAT_AGE:
            return False, (f"last heartbeat {self.heartbeat_age_s:.1f}s ago "
                           f"(limit {self.MAX_HEARTBEAT_AGE:.0f}s); the link "
                           f"drops at ~32s")
        return True, (f"both arms, MTU {self.mtu_left}/{self.mtu_right}, "
                      f"heartbeat {self.heartbeat_age_s:.1f}s old")


def summarize(verdicts: list[Verdict]) -> dict:
    """Counts per gate — the shape a soak report wants."""
    out: dict[str, int] = {"push": 0, "queue": 0}
    for v in verdicts:
        out[v.action] = out.get(v.action, 0) + 1
        out[f"gate:{v.gate}"] = out.get(f"gate:{v.gate}", 0) + 1
    return out